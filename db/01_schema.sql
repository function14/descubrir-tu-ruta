-- ---------- BASE DE CONOCIMIENTO ----------
CREATE TABLE variable (
  id_variable INTEGER PRIMARY KEY,
  nombre      VARCHAR(40) NOT NULL UNIQUE
);
CREATE TABLE valor (
  id_valor    INTEGER PRIMARY KEY,
  id_variable INTEGER NOT NULL REFERENCES variable(id_variable),
  etiqueta    VARCHAR(40) NOT NULL,
  UNIQUE (id_variable, etiqueta)
);
CREATE TABLE destino (            -- hipótesis
  id_destino  INTEGER PRIMARY KEY,
  nombre      VARCHAR(80) NOT NULL UNIQUE,
  region      VARCHAR(60),
  descripcion VARCHAR(200),
  activo      INTEGER NOT NULL DEFAULT 1 CHECK (activo IN (0,1))
);
CREATE TABLE arbol (
  id_arbol INTEGER PRIMARY KEY,
  nombre   VARCHAR(60) NOT NULL UNIQUE
);
CREATE TABLE regla (
  id_regla   INTEGER PRIMARY KEY,
  codigo     VARCHAR(10) NOT NULL UNIQUE,
  id_arbol   INTEGER NOT NULL REFERENCES arbol(id_arbol),
  id_destino INTEGER NOT NULL REFERENCES destino(id_destino),
  peso       DECIMAL(4,2) NOT NULL DEFAULT 1.0,
  activa     INTEGER NOT NULL DEFAULT 1 CHECK (activa IN (0,1))
);
CREATE TABLE regla_condicion (    -- gránulo de conocimiento
  id_regla    INTEGER NOT NULL REFERENCES regla(id_regla),
  id_variable INTEGER NOT NULL REFERENCES variable(id_variable),
  id_valor    INTEGER NOT NULL REFERENCES valor(id_valor),
  PRIMARY KEY (id_regla, id_variable)
);

-- ---------- BASE TRANSACCIONAL ----------
CREATE TABLE rol (
  id_rol INTEGER PRIMARY KEY,
  nombre VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE usuario (
  id_usuario    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        VARCHAR(80) NOT NULL,
  email         VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  id_rol        INTEGER NOT NULL REFERENCES rol(id_rol),
  creado_en     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE consulta (
  id_consulta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario  INTEGER NOT NULL REFERENCES usuario(id_usuario),
  fecha       TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE respuesta_usuario (  -- hechos
  id_consulta INTEGER NOT NULL REFERENCES consulta(id_consulta),
  id_variable INTEGER NOT NULL REFERENCES variable(id_variable),
  id_valor    INTEGER NOT NULL REFERENCES valor(id_valor),
  PRIMARY KEY (id_consulta, id_variable)
);
CREATE TABLE recomendacion (
  id_consulta INTEGER NOT NULL REFERENCES consulta(id_consulta),
  posicion    INTEGER NOT NULL CHECK (posicion BETWEEN 1 AND 3),
  id_destino  INTEGER NOT NULL REFERENCES destino(id_destino),
  puntaje     DECIMAL(6,2) NOT NULL,
  PRIMARY KEY (id_consulta, posicion)
);
CREATE TABLE recomendacion_regla ( -- trazabilidad: reglas disparadas
  id_consulta INTEGER NOT NULL REFERENCES consulta(id_consulta),
  id_regla    INTEGER NOT NULL REFERENCES regla(id_regla),
  PRIMARY KEY (id_consulta, id_regla)
);
