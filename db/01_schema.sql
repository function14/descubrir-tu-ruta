-- DDL de la base de conocimiento y la base transaccional.
-- Portado de sistema_experto_turismo.sql (SQLite). Cambios del port:
--   * se elimina PRAGMA foreign_keys (Postgres siempre valida las FK)
--   * usuario y consulta usan IDENTITY: en Postgres INTEGER PRIMARY KEY
--     no autoincrementa, y la API crea filas en consulta
